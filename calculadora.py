def sumar(a, b):
    """
    Esta función toma dos números y devuelve su suma.

    :param a: Primer número
    :param b: Segundo número
    :return: Suma de a y b
    """
    return a + b


def restar(a, b):
    """
    Esta función toma dos números y devuelve su resta.

    :param a: Primer número
    :param b: Segundo número
    :return: Resta de a y b
    """
    return a - b
